// Intake for "Tool Promo" — pick which tool from the catalog you want to
// promote, then fine-tune the prompt. Reuses PromptEditor in
// product_launch mode (the prompt + paste-details layout already fits a
// product/tool walk-through).
//
// Picking a tool seeds:
//  • state.name           — "<Tool> Promo"
//  • state.prompt         — 1-scene 30s promo prompt for that tool
//  • state.resumeText     — tool title, description, features, audience
//                           (the script generator reads this as context)
//
// One scene only — Studio's storyboard generator will produce a single
// scene because the prompt explicitly asks for it.

import { useMemo } from "react";
import { Sparkles } from "lucide-react";
import PromptEditor from "@/components/PromptEditor";
import { Label } from "@/components/ui/label";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { TOOLS_CATALOG, type ToolCatalogEntry } from "@/data/tools-catalog";
import type { IntakeProps } from "../catalog";
import { useState } from "react";

const PROMO_TOOL_ID_MARKER = "[promo-tool:";

function buildToolContext(tool: ToolCatalogEntry): string {
  const lines = [
    `Tool: ${tool.title}`,
    `Description: ${tool.description}`,
  ];
  if (tool.features?.length) {
    lines.push(`Features:\n- ${tool.features.join("\n- ")}`);
  }
  if (tool.stats) {
    const stats = tool.stats.map((s) => `${s.value} ${s.label}`).join(", ");
    lines.push(`Highlights: ${stats}`);
  }
  if (tool.ctaLabel) lines.push(`Call to action: ${tool.ctaLabel}`);
  // Trailing marker lets us round-trip which tool this promo is for —
  // detected by `extractPromoToolId` so the publish flow can attach the
  // resulting video URL back to the catalog entry.
  lines.push(`${PROMO_TOOL_ID_MARKER}${tool.id}]`);
  return lines.join("\n");
}

function buildPromoPrompt(tool: ToolCatalogEntry): string {
  return `Create a single-scene 30-second promo video for the "${tool.title}" tool. ${tool.description}. Open with the problem the tool solves, then show the tool in use (screen capture + voiceover), then end with a clear "${tool.ctaLabel ?? "Try it now"}" call to action. One scene only — no chapters, no transitions.`;
}

/** Pull the tool id out of a previously-saved resumeText, so reopening
 *  the project restores the picker's selected value. Returns null if
 *  the text wasn't generated by this intake. Exported so the publish
 *  flow can use the same parser. */
export function extractPromoToolId(resumeText: string): string | null {
  const idx = resumeText.indexOf(PROMO_TOOL_ID_MARKER);
  if (idx === -1) return null;
  const tail = resumeText.slice(idx + PROMO_TOOL_ID_MARKER.length);
  const close = tail.indexOf("]");
  if (close === -1) return null;
  const id = tail.slice(0, close).trim();
  return id || null;
}

export default function ToolPromoIntake({
  state,
  onStateChange,
  validationFlash,
  onLinkSubject,
}: IntakeProps) {
  const initialId = useMemo(
    () => extractPromoToolId(state.resumeText) ?? "",
    // Only seed once on mount — typing in the prompt shouldn't re-derive.
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [],
  );
  const [selectedId, setSelectedId] = useState<string>(initialId);
  const [showJD, setShowJD] = useState(false);

  function handlePick(id: string) {
    setSelectedId(id);
    const tool = TOOLS_CATALOG.find((t) => t.id === id);
    if (!tool) return;
    onStateChange({
      name: `${tool.title} Promo`,
      prompt: buildPromoPrompt(tool),
      resumeText: buildToolContext(tool),
    });
  }

  return (
    <div className="flex flex-col gap-4 p-4">
      <div className="rounded-lg border bg-muted/30 p-4">
        <div className="flex items-center gap-2 mb-2">
          <Sparkles className="w-4 h-4 text-primary" aria-hidden="true" />
          <Label className="text-sm font-semibold">Which tool are you promoting?</Label>
        </div>
        <p className="text-xs text-muted-foreground mb-3">
          Pick a tool from the catalog. We'll seed a 30-second one-scene
          promo prompt and fill in the tool's features as context for the
          script generator. You can edit everything below.
        </p>
        <Select value={selectedId} onValueChange={handlePick}>
          <SelectTrigger className="w-full">
            <SelectValue placeholder="Select a tool…" />
          </SelectTrigger>
          <SelectContent>
            {TOOLS_CATALOG.map((tool) => (
              <SelectItem key={tool.id} value={tool.id}>
                {tool.title}
              </SelectItem>
            ))}
          </SelectContent>
        </Select>
      </div>

      <PromptEditor
        state={state}
        onStateChange={onStateChange}
        showJD={showJD}
        onToggleJD={() => setShowJD((v) => !v)}
        validationFlash={validationFlash}
        onLinkSubject={onLinkSubject}
      />
    </div>
  );
}
