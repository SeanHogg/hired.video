const targets = [
  ["public/locales/en.json", en],
  ["public/locales/es.json", es],
  ["public/locales/fr-CA.json", fr],
];

for (const [path, add] of targets) {
  const j = JSON.parse(readFileSync(path, "utf8"));
  let added = 0;
  for (const [k, v] of Object.entries(add)) {
    if (!(k in j)) added++;
    j[k] = v;
  }
  writeFileSync(path, JSON.stringify(j, null, 2) + "\n", "utf8");
  console.log(`${path}: +${added} keys (total ${Object.keys(j).length})`);
}
