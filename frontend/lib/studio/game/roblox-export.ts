/**
 * Roblox `.rbxlx` exporter — emits a Roblox place file from a
 * `World3DState` (gap #1661). Generates the human-readable XML
 * variant of Roblox's place format so the file opens cleanly in
 * Roblox Studio and the format stays diff-able.
 *
 * Scope (v1):
 *   - Every entity becomes a `Part` under Workspace.
 *   - Position + Size + BrickColor (approximated from the entity's
 *     hex color → nearest Roblox BrickColor).
 *   - Anchored (static) by default; dynamic entities become non-
 *     anchored.
 *   - Ground plane → a single large anchored Part for the floor.
 *
 * Out of scope (tracked under #1661):
 *   - Lua scripts (challenge logic, weapon behavior, character
 *     controller). Roblox needs Luau; translating our challenge
 *     reducer + agent tools to scripts is its own project.
 *   - Textures (would need Roblox asset IDs; image upload is a
 *     creator-account-gated flow).
 *   - Lighting / sky settings.
 *   - Collectibles + goals + hazards as Roblox triggers (would
 *     need `Touched` event scripts).
 *   - Player spawn point → SpawnLocation Part (easy follow-on).
 */

import type {
  GameState,
  World3DEntity,
  World3DState,
} from "@shared/game-state";
// Shared XML text escaper (single source of truth — register gap #1942).
// Same `&`/`<`/`>`/`"`/`'` set as the prior local copy; the apostrophe is
// emitted as `&#39;` rather than `&apos;` — both parse to a literal `'` in
// any conformant XML parser, so the generated `.rbxlx` is equivalent.
import { escapeXmlText as escapeXml } from "@shared/course-cover";

const RBX_VERSION = "4";

/** Generate the `.rbxlx` XML for the 3D-world game state. */
export function exportToRobloxXml(gameState: GameState, projectName = "HiredWorld"): string {
  if (gameState.engine !== "world-3d" || !gameState.world) {
    throw new Error("Roblox export requires a world-3d gameState with a populated world.");
  }
  const world = gameState.world;
  const parts: string[] = [];
  let ref = 0;
  const nextRef = () => `RBX${ref++}`;

  // ─── Ground plane ─────────────────────────────────────────────────────
  parts.push(renderPart({
    ref: nextRef(),
    name: "Ground",
    centerY: -0.5,
    size: [world.ground.size, 1, world.ground.size],
    color: world.ground.color,
    anchored: true,
  }));

  // ─── SpawnLocation ────────────────────────────────────────────────────
  parts.push(renderSpawn({
    ref: nextRef(),
    position: world.spawn.position,
  }));

  // ─── Entities ─────────────────────────────────────────────────────────
  for (const entity of world.entities) {
    parts.push(renderPart({
      ref: nextRef(),
      name: `${entity.kind}-${entity.id}`,
      centerY: entity.position[1],
      center: entity.position,
      size: entity.scale,
      color: entity.color,
      anchored: entity.physics !== "dynamic",
      transparency: entity.kind === "goal" ? 0.6 : 0,
    }));
  }

  return `<roblox version="${RBX_VERSION}">
  <External>null</External>
  <External>nil</External>
  <Item class="Workspace" referent="RBX_WORKSPACE">
    <Properties>
      <string name="Name">Workspace</string>
    </Properties>
    <!-- Generated by hired.video Studio (3D World) -->
    <!-- Project: ${escapeXml(projectName)} -->
${parts.map((p) => indent(p, 4)).join("\n")}
  </Item>
</roblox>
`;
}

interface PartArgs {
  ref: string;
  name: string;
  /** Optional explicit center. When omitted, defaults to (0, centerY, 0). */
  center?: [number, number, number];
  centerY: number;
  size: [number, number, number];
  color: string;
  anchored: boolean;
  /** 0 = opaque, 1 = invisible. Default 0. */
  transparency?: number;
}

function renderPart(p: PartArgs): string {
  const [cx, cy, cz] = p.center ?? [0, p.centerY, 0];
  const [, g, b] = hexToRgb(p.color);
  const r = hexToRgb(p.color)[0];
  return `<Item class="Part" referent="${p.ref}">
  <Properties>
    <string name="Name">${escapeXml(p.name)}</string>
    <bool name="Anchored">${p.anchored ? "true" : "false"}</bool>
    <CoordinateFrame name="CFrame">
      <X>${cx}</X>
      <Y>${cy}</Y>
      <Z>${cz}</Z>
      <R00>1</R00><R01>0</R01><R02>0</R02>
      <R10>0</R10><R11>1</R11><R12>0</R12>
      <R20>0</R20><R21>0</R21><R22>1</R22>
    </CoordinateFrame>
    <Vector3 name="size">
      <X>${p.size[0]}</X>
      <Y>${p.size[1]}</Y>
      <Z>${p.size[2]}</Z>
    </Vector3>
    <Color3 name="Color3">
      <R>${(r / 255).toFixed(4)}</R>
      <G>${(g / 255).toFixed(4)}</G>
      <B>${(b / 255).toFixed(4)}</B>
    </Color3>
    <float name="Transparency">${p.transparency ?? 0}</float>
  </Properties>
</Item>`;
}

function renderSpawn(args: { ref: string; position: [number, number, number] }): string {
  const [x, y, z] = args.position;
  return `<Item class="SpawnLocation" referent="${args.ref}">
  <Properties>
    <string name="Name">SpawnLocation</string>
    <bool name="Anchored">true</bool>
    <CoordinateFrame name="CFrame">
      <X>${x}</X>
      <Y>${y}</Y>
      <Z>${z}</Z>
      <R00>1</R00><R01>0</R01><R02>0</R02>
      <R10>0</R10><R11>1</R11><R12>0</R12>
      <R20>0</R20><R21>0</R21><R22>1</R22>
    </CoordinateFrame>
    <Vector3 name="size">
      <X>4</X>
      <Y>0.5</Y>
      <Z>4</Z>
    </Vector3>
    <Color3 name="Color3">
      <R>0.3</R><G>0.7</G><B>0.3</B>
    </Color3>
  </Properties>
</Item>`;
}

// ─── Helpers ───────────────────────────────────────────────────────────

function hexToRgb(hex: string): [number, number, number] {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex.trim());
  if (!m) return [128, 128, 128];
  const n = parseInt(m[1], 16);
  return [(n >> 16) & 0xff, (n >> 8) & 0xff, n & 0xff];
}

function indent(s: string, n: number): string {
  const pad = " ".repeat(n);
  return s.split("\n").map((line) => (line ? pad + line : line)).join("\n");
}

/** Browser-side download trigger. Builds a Blob from the XML and
 *  hands it to a hidden `<a download>` so the user gets a file save
 *  prompt. Self-gated when called server-side (no-op). */
export function downloadRobloxFile(gameState: GameState, filename = "hired-world.rbxlx"): void {
  if (typeof window === "undefined") return;
  const xml = exportToRobloxXml(gameState, filename.replace(/\.rbxlx$/i, ""));
  const blob = new Blob([xml], { type: "application/xml" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

// Re-export with World3DState param too for tests / advanced callers.
export function exportWorldToRobloxXml(world: World3DState, projectName = "HiredWorld"): string {
  // Wrap in a minimal GameState so we can reuse the same renderer.
  return exportToRobloxXml(
    {
      schemaVersion: 1,
      engine: "world-3d",
      width: 1280,
      height: 720,
      fps: 60,
      levels: [],
      startLevelId: "",
      assets: [],
      world,
    },
    projectName,
  );
}

