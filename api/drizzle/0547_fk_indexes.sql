-- 0547_fk_indexes.sql
--
-- W1-D data-model hygiene (architecture remediation 2026-10-17).
--
-- Postgres does not index foreign-key columns. 268 FK columns had no index
-- whose LEADING column is the FK, so every parent delete / ON DELETE cascade
-- or SET NULL, and every "children of X" read, seq-scanned the child table
-- (deleting one user scanned ~150 tables). Found by
--   node --import tsx scripts/find-unindexed-fks.ts
-- which now reports 0. Plus idx_job_board_postings_job_id (job postings are
-- listed by job_id; the table had no secondary index).
--
-- Every index is declared in api/src/db/schema under the same name
-- (`idx_<table>_<column>`), so `drizzle-kit push` creates it on deploy before
-- this file runs; this file is the record + fallback for any database where
-- push did not. Plain CREATE INDEX IF NOT EXISTS: push creates them the same
-- way, and the runner sends each statement separately.

