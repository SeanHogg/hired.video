-- Migration 0093 — Usage Ledger, Monthly Statements, Free + Paid Invoices.
--
-- Centralises every metered consumption event behind a single ledger so the
-- ServicesProcessor domain has one place to record AI tokens, video publishes,
-- team invites, interview sessions, saved searches, company-DB writes, and
-- per-tool calls. The Pricing-page audit (gap-register #765-#770) found six
-- different limits advertised on /pricing with no backing enforcement; this
-- migration is the storage half of the fix.
--
-- Tables:
--
--   1. `usage_ledger`        — append-only event log. Every gate/meter call
--                              writes one row. Keyed by (user_id, event_type,
--                              period_start) for fast monthly rollups.
--                              `quantity` is the unit-of-measure for that
--                              event_type (tokens for ai_tokens, count for
--                              everything else).
--
--   2. `usage_statements`    — monthly per-user roll-up snapshot. One row per
--                              (user_id, period_start) with included_quantity
--                              (plan allowance), consumed_quantity (ledger
--                              sum), overage_quantity, and overage_cents.
--                              Generated by the month-close cron OR on-demand
--                              when the Settings page asks for the current
--                              period. The current-month row is the "preview";
--                              past months are frozen invoices.
--
--   3. `usage_invoices`      — per-month invoice (including $0 Free Invoice).
--                              Linked to the closing statement, holds the
--                              total + currency + plan tier + email-sent
--                              timestamp so the cron is idempotent.
--
-- ServicesProcessor calls these via the repositories layer; no route writes
-- directly. See [api/src/domains/services-processing/services-processor.ts].

-- ── usage_ledger ───────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS usage_ledger (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id         UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    -- enum-like text matched against the ServicesProcessor catalog:
    --   ai_tokens | video_publish | team_invite | interview_session |
    --   saved_search | company_db_write | resume_tailor | resume_roast |
    --   resume_summary | value_prop_pitch | resume_parse | career_coach_msg |
    --   export_4k | export_1080p | bulk_score_run
    event_type      TEXT NOT NULL,
    -- Plan tier at the time the event was recorded ("free" | "pro" | "trial").
    -- Persisted so historical statements remain stable if the user later
    -- changes plans mid-month.
    plan            TEXT NOT NULL,
    -- Quantity of the metered unit:
    --   ai_tokens             → token count
    --   everything else       → 1 (count of occurrences) or N for batched ops
    quantity        BIGINT NOT NULL DEFAULT 1,
    -- The monthly bucket this event rolls up into (UTC first-of-month at
    -- 00:00:00). Computed at insert time so the cron groups deterministically.
    period_start    TIMESTAMPTZ NOT NULL,
    -- Optional foreign-key style links back to the source row that caused the
    -- meter call, kept as JSONB so we don't grow the column list every time a
    -- new event_type is added. Common keys: { resourceId, toolRunId,
    -- projectId, sessionId, model, featureKey }.
    metadata        JSONB,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS usage_ledger_user_period_idx
    ON usage_ledger (user_id, period_start, event_type);

CREATE INDEX IF NOT EXISTS usage_ledger_period_idx
    ON usage_ledger (period_start);

CREATE INDEX IF NOT EXISTS usage_ledger_created_at_idx
    ON usage_ledger (created_at);

-- ── usage_statements ──────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS usage_statements (
    id                      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id                 UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    period_start            TIMESTAMPTZ NOT NULL,
    period_end              TIMESTAMPTZ NOT NULL,
    plan                    TEXT NOT NULL,
    -- JSONB array of { eventType, label, unit, includedQuantity,
    -- consumedQuantity, overageQuantity, overageCents } so we don't need a
    -- side table for every metered dimension.
    lines                   JSONB NOT NULL DEFAULT '[]'::jsonb,
    total_cents             INTEGER NOT NULL DEFAULT 0,
    currency                TEXT NOT NULL DEFAULT 'USD',
    -- 'open' while the period is current and the cron has not closed it;
    -- 'closed' after the month-end roll-up; 'voided' for refunds / disputes.
    status                  TEXT NOT NULL DEFAULT 'open',
    closed_at               TIMESTAMPTZ,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- One statement per (user, period) — keeps the cron idempotent and lets
    -- the Settings page upsert the live preview.
    CONSTRAINT usage_statements_user_period_unique
        UNIQUE (user_id, period_start)
);

CREATE INDEX IF NOT EXISTS usage_statements_user_idx
    ON usage_statements (user_id, period_start DESC);

CREATE INDEX IF NOT EXISTS usage_statements_status_period_idx
    ON usage_statements (status, period_end);

-- ── usage_invoices ────────────────────────────────────────────────────────
-- Both Free ($0) and paid invoices live here. Stays separate from the
-- existing `invoices` table (Stripe / Helcim payment receipts) because:
--   • usage_invoices is generated for every user every month, paid or not
--   • the existing `invoices` table is keyed to a payment_provider + external
--     invoice ID and assumes a money-moving event
-- The link goes statement -> usage_invoice -> (optional) invoices.id when a
-- charge is actually made.
CREATE TABLE IF NOT EXISTS usage_invoices (
    id                      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id                 UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    statement_id            UUID NOT NULL REFERENCES usage_statements(id) ON DELETE CASCADE,
    period_start            TIMESTAMPTZ NOT NULL,
    period_end              TIMESTAMPTZ NOT NULL,
    plan                    TEXT NOT NULL,
    invoice_number          TEXT NOT NULL,
    total_cents             INTEGER NOT NULL DEFAULT 0,
    currency                TEXT NOT NULL DEFAULT 'USD',
    -- 'free_zero' when total_cents = 0 and plan = 'free' (the close-out Free
    -- Invoice the user asked for). 'paid' / 'pending' / 'failed' /
    -- 'refunded' for the standard money-moving cases.
    status                  TEXT NOT NULL DEFAULT 'pending',
    payment_invoice_id      UUID,  -- ID into the existing `invoices` table when a real charge applies. Nullable for $0 Free invoices.
    email_sent_at           TIMESTAMPTZ,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT usage_invoices_user_period_unique
        UNIQUE (user_id, period_start)
);

CREATE INDEX IF NOT EXISTS usage_invoices_user_idx
    ON usage_invoices (user_id, period_start DESC);

CREATE INDEX IF NOT EXISTS usage_invoices_status_idx
    ON usage_invoices (status, created_at DESC);

CREATE UNIQUE INDEX IF NOT EXISTS usage_invoices_number_unique
    ON usage_invoices (invoice_number);
