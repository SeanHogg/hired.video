/**
 * Location sitemap generator (#1666) — emits frontend/public/sitemap-locations.xml
 * with one <url> per launch-market /in/[country], /in/[country]/[state],
 * and /in/[country]/[state]/[city] page.
 *
 * The main sitemap.xml hand-lists the country roots + /sitemap/locations;
 * this generator materializes the long-tail state + city URLs so crawlers
 * get full coverage without bloating the primary sitemap. Referenced from
 * robots.txt via a second `Sitemap:` directive.
 *
 * Mirrors the gating in GET /api/locations/sitemap:
 *   - launch markets only (US/CA/MX per shared/launch-markets.ts)
 *   - states deduped by lower(name) (defensive; 0167 also fixes the data)
 *   - cities deduped by slug; only cities with content OR population are
 *     emitted (a city with neither is a thin page Google would skip).
 *
 * Usage:  DATABASE_URL=… node scripts/generate-location-sitemap.mjs
 * Run in CI after migrations + any content/geo refresh.
 */
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { neon } from "@neondatabase/serverless";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = join(__dirname, "../../frontend/public/sitemap-locations.xml");
const BASE = "https://hired.video";

// Keep in sync with shared/launch-markets.ts PROMOTABLE_MARKET_ISO2.
const PROMOTABLE = ["US", "CA", "MX"];

function xmlEscape(s) {
  return String(s).replace(/[<>&'"]/g, (ch) => (
    { "<": "&lt;", ">": "&gt;", "&": "&amp;", "'": "&apos;", '"': "&quot;" }[ch]
  ));
}

function urlTag(loc, priority) {
  return `  <url><loc>${xmlEscape(loc)}</loc><changefreq>weekly</changefreq><priority>${priority}</priority></url>`;
}

async function main() {
  const url = process.env.DATABASE_URL || process.env.NEON_DATABASE_URL || process.env.NEON_DB_URL;
  if (!url) {
    console.error("DATABASE_URL is not set");
    process.exit(1);
  }
  const sql = neon(url);

  const placeholders = PROMOTABLE.map((_, i) => `$${i + 1}`).join(", ");
  const rows = await sql(
    `SELECT co.iso2 AS country_iso, co.name AS country_name,
            sp.id AS state_id, sp.name AS state_name, sp.code AS state_code,
            c.id AS city_id, c.name AS city_name, c.slug AS city_slug,
            c.population AS city_population
     FROM countries co
     LEFT JOIN state_provinces sp ON sp.country_id = co.id AND sp.is_active = true
     LEFT JOIN cities c ON c.state_id = sp.id AND c.is_active = true
     WHERE co.is_active = true AND upper(co.iso2) IN (${placeholders})
     ORDER BY co.name, sp.name, c.population DESC NULLS LAST, c.name`,
    PROMOTABLE,
  );

  const lines = [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<!-- Generated by api/scripts/generate-location-sitemap.mjs (#1666). DO NOT EDIT BY HAND. -->`,
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">`,
  ];

  const seenCountries = new Set();
  const seenStates = new Set();   // key: `${iso}/${stateNameLower}`
  const seenCities = new Set();   // key: `${iso}/${stateSlug}/${citySlug}`

  for (const r of rows) {
    const iso = r.country_iso.toLowerCase();
    if (!seenCountries.has(iso)) {
      seenCountries.add(iso);
      lines.push(urlTag(`${BASE}/in/${iso}`, "0.7"));
    }
    if (r.state_id) {
      const stateSlug = String(r.state_code ?? r.state_name).toLowerCase();
      const stateKey = `${iso}/${String(r.state_name).toLowerCase()}`;
      if (!seenStates.has(stateKey)) {
        seenStates.add(stateKey);
        lines.push(urlTag(`${BASE}/in/${iso}/${encodeURIComponent(stateSlug)}`, "0.6"));
      }
      // Only emit cities that have content potential — a known population
      // (seeded/imported) keeps thin, never-populated stub pages out of
      // the sitemap. Content-count gating can layer on later.
      if (r.city_id && r.city_population != null) {
        const cityKey = `${iso}/${stateSlug}/${r.city_slug}`;
        if (!seenCities.has(cityKey)) {
          seenCities.add(cityKey);
          lines.push(urlTag(`${BASE}/in/${iso}/${encodeURIComponent(stateSlug)}/${encodeURIComponent(r.city_slug)}`, "0.5"));
        }
      }
    }
  }

  lines.push(`</urlset>`, "");
  writeFileSync(OUT_PATH, lines.join("\n"), "utf8");
  console.log(
    `sitemap-locations.xml: ${seenCountries.size} countries, ${seenStates.size} states, ${seenCities.size} cities → ${OUT_PATH}`,
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
